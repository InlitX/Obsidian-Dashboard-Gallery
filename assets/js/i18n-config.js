let currentLang = 'en';

i18next
    .use(i18nextBrowserLanguageDetector)
    .init({
        resources: translations,
        fallbackLng: 'en',
        interpolation: { escapeValue: false }
    }, function(err) {
        if (err) console.log('i18n init error:', err);
        currentLang = i18next.language || localStorage.getItem('i18nextLng') || 'en';
        if (currentLang.length > 2) currentLang = currentLang.split('-')[0];
        updateContent();
        updateLangUI();
    });

function t(key) {
    return i18next.t(key);
}

function updateContent() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translated = t(key);
        if (translated && translated !== key) {
            el.textContent = translated;
        }
    });
}

function updateLangUI() {
    document.querySelectorAll('.lang-option').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === currentLang);
    });
    const label = document.getElementById('currentLangLabel');
    if (label) label.textContent = currentLang.toUpperCase();
}

document.addEventListener('DOMContentLoaded', () => {
    updateContent();
    
    const langTrigger = document.getElementById('langTrigger');
    const langMenu = document.getElementById('langMenu');
    
    if (langTrigger && langMenu) {
        langTrigger.addEventListener('click', (e) => {
            e.stopPropagation();
            langMenu.classList.toggle('active');
        });
        document.addEventListener('click', () => langMenu.classList.remove('active'));
        langMenu.addEventListener('click', (e) => e.stopPropagation());
        
        document.querySelectorAll('.lang-option').forEach(btn => {
            btn.addEventListener('click', () => {
                const lang = btn.dataset.lang;
                i18next.changeLanguage(lang, () => {
                    currentLang = lang;
                    updateContent();
                    updateLangUI();
                    localStorage.setItem('i18nextLng', lang);
                });
                langMenu.classList.remove('active');
            });
        });
    }
    
    fetch('https://api.github.com/repos/InlitX/Obsidian-Dashboard-Gallery')
        .then(res => res.json())
        .then(data => {
            if (data.stargazers_count) {
                const starEl = document.getElementById('stars-header');
                if (starEl) starEl.textContent = `Star ${data.stargazers_count}`;
            }
        })
        .catch(() => {});
});
